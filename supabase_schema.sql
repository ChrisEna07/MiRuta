-- 1. Tabla de Paquetes e Historial de Trazabilidad (packages)
CREATE TABLE IF NOT EXISTS public.packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  local_id BIGINT,
  tracking_number TEXT NOT NULL,
  last_four_digits TEXT NOT NULL,
  recipient_name TEXT NOT NULL DEFAULT 'Cliente iMile',
  recipient_phone TEXT DEFAULT '',
  raw_address TEXT NOT NULL,
  parsed_address JSONB DEFAULT '{}'::jsonb,
  coordinates JSONB DEFAULT NULL,
  delivery_coordinates JSONB DEFAULT NULL,
  route_order INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'pending',
  issue_note TEXT DEFAULT '',
  audit_note TEXT DEFAULT '',
  proof_photo_base64 TEXT DEFAULT NULL,
  rate NUMERIC NOT NULL DEFAULT 2200,
  shift_id TEXT NOT NULL,
  scanned_at BIGINT NOT NULL,
  arrived_at_point_at BIGINT DEFAULT NULL,
  wait_time_seconds INTEGER DEFAULT 0,
  delivered_at BIGINT DEFAULT NULL,
  archived_in_history BOOLEAN NOT NULL DEFAULT FALSE,
  is_test_data BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_packages_tracking_shift UNIQUE (tracking_number, shift_id)
);

CREATE INDEX IF NOT EXISTS idx_packages_shift_id ON public.packages (shift_id);
CREATE INDEX IF NOT EXISTS idx_packages_last_four ON public.packages (last_four_digits);
CREATE INDEX IF NOT EXISTS idx_packages_status ON public.packages (status);

-- 2. Tabla de Jornadas Diarias (shifts)
CREATE TABLE IF NOT EXISTS public.shifts (
  id TEXT PRIMARY KEY,
  date TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  started_at BIGINT DEFAULT NULL,
  end_time BIGINT DEFAULT NULL,
  is_paused BOOLEAN NOT NULL DEFAULT FALSE,
  last_pause_started_at BIGINT DEFAULT NULL,
  accumulated_paused_ms BIGINT NOT NULL DEFAULT 0,
  manual_active_minutes_offset INTEGER NOT NULL DEFAULT 0,
  effective_duration_ms BIGINT DEFAULT 0,
  fuel_expense NUMERIC NOT NULL DEFAULT 12000,
  other_expense NUMERIC NOT NULL DEFAULT 0,
  closed_delivered_count INTEGER DEFAULT 0,
  closed_gross_cop NUMERIC DEFAULT 0,
  closed_net_cop NUMERIC DEFAULT 0,
  sector_name TEXT DEFAULT 'Medellín - Ruta del Día',
  notes TEXT DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabla de Penalizaciones, Multas y Adelantos (deductions)
CREATE TABLE IF NOT EXISTS public.deductions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  local_id BIGINT UNIQUE,
  date TEXT NOT NULL,
  shift_id TEXT NOT NULL,
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  amount NUMERIC NOT NULL DEFAULT 0,
  tracking_number TEXT DEFAULT NULL,
  notes TEXT DEFAULT '',
  apply_to_juan_pdf BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Tabla de Conciliación y Auditoría Quincenal (settlements)
CREATE TABLE IF NOT EXISTS public.settlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_key TEXT UNIQUE NOT NULL,
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  expected_gross NUMERIC NOT NULL DEFAULT 0,
  total_deductions NUMERIC NOT NULL DEFAULT 0,
  expected_net NUMERIC NOT NULL DEFAULT 0,
  actual_paid_amount NUMERIC NOT NULL DEFAULT 0,
  paid_packages_count_reported_by_company INTEGER DEFAULT NULL,
  payment_date TEXT NOT NULL,
  payment_method TEXT NOT NULL DEFAULT 'Nequi',
  status TEXT NOT NULL DEFAULT 'pending',
  notes TEXT DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Bóveda Protegida de Snapshots y Auto-Backups por Fecha (backup_snapshots)
CREATE TABLE IF NOT EXISTS public.backup_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  local_id BIGINT,
  folder_date TEXT NOT NULL,
  timestamp TEXT UNIQUE NOT NULL,
  session_name TEXT NOT NULL,
  trigger_type TEXT NOT NULL DEFAULT 'manual_checkpoint',
  stats JSONB NOT NULL DEFAULT '{}'::jsonb,
  payload_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_backup_snapshots_folder_date ON public.backup_snapshots (folder_date);

-- Habilitar Row Level Security (RLS) con acceso para la Anon/Publishable Key
ALTER TABLE public.packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.deductions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settlements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.backup_snapshots ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir acceso completo MiRuta packages" ON public.packages;
CREATE POLICY "Permitir acceso completo MiRuta packages" ON public.packages FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso completo MiRuta shifts" ON public.shifts;
CREATE POLICY "Permitir acceso completo MiRuta shifts" ON public.shifts FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso completo MiRuta deductions" ON public.deductions;
CREATE POLICY "Permitir acceso completo MiRuta deductions" ON public.deductions FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso completo MiRuta settlements" ON public.settlements;
CREATE POLICY "Permitir acceso completo MiRuta settlements" ON public.settlements FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso completo MiRuta backup_snapshots" ON public.backup_snapshots;
CREATE POLICY "Permitir acceso completo MiRuta backup_snapshots" ON public.backup_snapshots FOR ALL USING (true) WITH CHECK (true);
